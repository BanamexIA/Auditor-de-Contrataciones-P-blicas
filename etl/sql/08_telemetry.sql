\set ON_ERROR_STOP on
\getenv telemetry_etl_user ETL_USER

CREATE SCHEMA IF NOT EXISTS telemetry;

CREATE TABLE IF NOT EXISTS telemetry.llm_calls (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at TIMESTAMPTZ NOT NULL,
    agent TEXT NOT NULL,
    provider TEXT NOT NULL,
    model TEXT NOT NULL,
    model_quantization TEXT,
    ollama_version TEXT,
    equipment TEXT NOT NULL,
    input_tokens INTEGER CHECK (input_tokens IS NULL OR input_tokens >= 0),
    output_tokens INTEGER CHECK (output_tokens IS NULL OR output_tokens >= 0),
    latency_ms DOUBLE PRECISION CHECK (latency_ms IS NULL OR latency_ms >= 0),
    tokens_per_second DOUBLE PRECISION
        CHECK (tokens_per_second IS NULL OR tokens_per_second >= 0),
    time_to_first_token_ms DOUBLE PRECISION
        CHECK (time_to_first_token_ms IS NULL OR time_to_first_token_ms >= 0),
    gpu_utilization_percent DOUBLE PRECISION
        CHECK (gpu_utilization_percent IS NULL OR gpu_utilization_percent BETWEEN 0 AND 100),
    vram_used_mb DOUBLE PRECISION CHECK (vram_used_mb IS NULL OR vram_used_mb >= 0),
    status TEXT NOT NULL CHECK (status IN ('success', 'error')),
    error_type TEXT,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS llm_calls_started_at_idx
    ON telemetry.llm_calls (started_at);
CREATE INDEX IF NOT EXISTS llm_calls_agent_model_idx
    ON telemetry.llm_calls (agent, model, started_at);

COMMENT ON TABLE telemetry.llm_calls IS
'Registro de llamadas a modelos LLM: proveedor, modelo, tokens, latencia y telemetría local disponible.';
COMMENT ON COLUMN telemetry.llm_calls.started_at IS
'Marca UTC de inicio de la llamada al modelo.';
COMMENT ON COLUMN telemetry.llm_calls.agent IS
'Agente o proceso que solicitó la generación.';
COMMENT ON COLUMN telemetry.llm_calls.provider IS
'Proveedor de inferencia, por ejemplo ollama o cloud.';
COMMENT ON COLUMN telemetry.llm_calls.model IS
'Identificador exacto del modelo utilizado.';
COMMENT ON COLUMN telemetry.llm_calls.model_quantization IS
'Cuantización reportada por la API del modelo; NULL cuando no está disponible.';
COMMENT ON COLUMN telemetry.llm_calls.ollama_version IS
'Versión obtenida de la API de Ollama; NULL para proveedores que no aplican.';
COMMENT ON COLUMN telemetry.llm_calls.equipment IS
'Nombre del equipo y plataforma donde corre el cliente que instrumenta la llamada.';
COMMENT ON COLUMN telemetry.llm_calls.input_tokens IS
'Tokens de entrada reportados por el proveedor.';
COMMENT ON COLUMN telemetry.llm_calls.output_tokens IS
'Tokens de salida reportados por el proveedor.';
COMMENT ON COLUMN telemetry.llm_calls.latency_ms IS
'Latencia total medida de la solicitud, en milisegundos.';
COMMENT ON COLUMN telemetry.llm_calls.tokens_per_second IS
'Velocidad de generación reportada por el proveedor o calculada con latencia total.';
COMMENT ON COLUMN telemetry.llm_calls.time_to_first_token_ms IS
'Estimación del tiempo al primer token en milisegundos, derivada de duraciones Ollama; NULL si no se reporta.';
COMMENT ON COLUMN telemetry.llm_calls.gpu_utilization_percent IS
'Máxima utilización NVIDIA observada localmente durante la llamada; NULL si no se mide.';
COMMENT ON COLUMN telemetry.llm_calls.vram_used_mb IS
'Máxima VRAM NVIDIA agregada observada localmente durante la llamada; NULL si no se mide.';
COMMENT ON COLUMN telemetry.llm_calls.status IS
'Resultado de la llamada: success o error. Las llamadas fallidas no tienen tokens.';
COMMENT ON COLUMN telemetry.llm_calls.error_type IS
'Tipo de excepción de una llamada fallida, sin guardar prompts ni mensajes que puedan contener datos.';
COMMENT ON COLUMN telemetry.llm_calls.recorded_at IS
'Marca de inserción del registro en PostgreSQL.';

GRANT USAGE ON SCHEMA telemetry TO :"telemetry_etl_user";
GRANT SELECT, INSERT ON telemetry.llm_calls TO :"telemetry_etl_user";
GRANT USAGE, SELECT ON SEQUENCE telemetry.llm_calls_id_seq TO :"telemetry_etl_user";
