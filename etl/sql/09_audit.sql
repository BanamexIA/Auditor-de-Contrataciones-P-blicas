\set ON_ERROR_STOP on

BEGIN;

CREATE SCHEMA IF NOT EXISTS audit;
REVOKE ALL ON SCHEMA audit FROM PUBLIC;

CREATE TABLE IF NOT EXISTS audit.bitacora (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    caso_id TEXT NOT NULL,
    etapa TEXT,
    evento TEXT NOT NULL,
    detalle JSONB NOT NULL DEFAULT '{}'::JSONB,
    modelo TEXT,
    equipo TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS bitacora_caso_created_at_idx
    ON audit.bitacora (caso_id, created_at);

COMMENT ON TABLE audit.bitacora IS
'Bitácora de eventos de casos. La estructura se crea en esta fase; su escritura aún no está implementada.';
COMMENT ON COLUMN audit.bitacora.id IS
'Identificador único del evento de bitácora.';
COMMENT ON COLUMN audit.bitacora.caso_id IS
'Identificador del caso asociado al evento.';
COMMENT ON COLUMN audit.bitacora.etapa IS
'Etapa del flujo a la que corresponde el evento, si aplica.';
COMMENT ON COLUMN audit.bitacora.evento IS
'Tipo o nombre del evento registrado.';
COMMENT ON COLUMN audit.bitacora.detalle IS
'Metadatos estructurados del evento; no debe contener secretos ni prompts con datos sensibles.';
COMMENT ON COLUMN audit.bitacora.modelo IS
'Identificador del modelo utilizado en el evento, si aplica.';
COMMENT ON COLUMN audit.bitacora.equipo IS
'Equipo que originó el evento, si aplica.';
COMMENT ON COLUMN audit.bitacora.created_at IS
'Marca de tiempo UTC en que se registró el evento.';

CREATE TABLE IF NOT EXISTS audit.reportes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    caso_id TEXT NOT NULL,
    s3_uri TEXT NOT NULL,
    sha256 TEXT NOT NULL CHECK (sha256 ~* '^[0-9a-f]{64}$'),
    version TEXT NOT NULL,
    modelo TEXT,
    equipo TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS reportes_caso_created_at_idx
    ON audit.reportes (caso_id, created_at);

COMMENT ON TABLE audit.reportes IS
'Metadatos y ubicación de reportes almacenados en S3. La lógica de generación y carga aún no está implementada.';
COMMENT ON COLUMN audit.reportes.id IS
'Identificador único del registro de reporte.';
COMMENT ON COLUMN audit.reportes.caso_id IS
'Identificador del caso al que pertenece el reporte.';
COMMENT ON COLUMN audit.reportes.s3_uri IS
'URI del objeto almacenado en el bucket privado de reportes.';
COMMENT ON COLUMN audit.reportes.sha256 IS
'Hash SHA-256 hexadecimal del contenido del reporte.';
COMMENT ON COLUMN audit.reportes.version IS
'Versión del reporte dentro del caso.';
COMMENT ON COLUMN audit.reportes.modelo IS
'Identificador del modelo utilizado para generar el reporte, si aplica.';
COMMENT ON COLUMN audit.reportes.equipo IS
'Equipo desde el que se generó el reporte, si aplica.';
COMMENT ON COLUMN audit.reportes.created_at IS
'Marca de tiempo UTC de creación del registro.';

CREATE TABLE IF NOT EXISTS audit.agentes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario TEXT NOT NULL,
    nombre_tailnet TEXT NOT NULL,
    modelo TEXT,
    estado TEXT NOT NULL DEFAULT 'desconocido',
    ultima_verificacion TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS agentes_usuario_idx
    ON audit.agentes (usuario);

COMMENT ON TABLE audit.agentes IS
'Registro de equipos de inferencia asociados a usuarios. La verificación y administración aún no están implementadas.';
COMMENT ON COLUMN audit.agentes.id IS
'Identificador único del registro de agente.';
COMMENT ON COLUMN audit.agentes.usuario IS
'Usuario propietario o responsable del equipo de inferencia.';
COMMENT ON COLUMN audit.agentes.nombre_tailnet IS
'Nombre del equipo registrado en la red Tailscale.';
COMMENT ON COLUMN audit.agentes.modelo IS
'Modelo disponible en el equipo, si se conoce.';
COMMENT ON COLUMN audit.agentes.estado IS
'Estado reportado del agente; se conserva como texto para permitir estados operativos futuros.';
COMMENT ON COLUMN audit.agentes.ultima_verificacion IS
'Marca de tiempo UTC de la última verificación del agente; NULL si aún no se ha verificado.';

REVOKE ALL ON audit.bitacora, audit.reportes, audit.agentes FROM PUBLIC;
REVOKE ALL ON SEQUENCE audit.bitacora_id_seq, audit.reportes_id_seq, audit.agentes_id_seq FROM PUBLIC;

COMMIT;
