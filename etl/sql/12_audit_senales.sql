\set ON_ERROR_STOP on
-- El backend se conecta con ETL_USER (ver DB_USER en docker-compose.yml).
\getenv senales_backend_user ETL_USER

BEGIN;

CREATE TABLE IF NOT EXISTS audit.senales (
    id TEXT PRIMARY KEY,
    caso_id TEXT NOT NULL REFERENCES audit.casos (id),
    tipo TEXT NOT NULL CHECK (length(btrim(tipo)) > 0),
    datos JSONB NOT NULL DEFAULT '{}'::JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS senales_caso_idx ON audit.senales (caso_id, created_at);

COMMENT ON TABLE audit.senales IS
'Señales de riesgo generadas por la Tool 1 para un caso. Una señal no es una determinación de fraude.';
COMMENT ON COLUMN audit.senales.id IS 'Identificador de la señal (UUID en texto).';
COMMENT ON COLUMN audit.senales.caso_id IS 'Caso al que pertenece la señal.';
COMMENT ON COLUMN audit.senales.tipo IS 'Tipo de regla que generó la señal.';
COMMENT ON COLUMN audit.senales.datos IS
'Criterio, valor, umbral y evidencia de la señal; su forma la define el contrato 1.';
COMMENT ON COLUMN audit.senales.created_at IS 'Marca de tiempo UTC en que se registró la señal.';

CREATE TABLE IF NOT EXISTS audit.decisiones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    caso_id TEXT NOT NULL REFERENCES audit.casos (id),
    senal_id TEXT NOT NULL REFERENCES audit.senales (id),
    decision TEXT NOT NULL CHECK (decision IN ('relevante', 'descartada', 'pendiente')),
    comentario TEXT,
    decidido_por TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT decisiones_descarte_con_comentario CHECK (
        decision <> 'descartada' OR length(btrim(coalesce(comentario, ''))) > 0
    )
);

CREATE INDEX IF NOT EXISTS decisiones_senal_idx ON audit.decisiones (senal_id, created_at DESC, id DESC);

COMMENT ON TABLE audit.decisiones IS
'Historial de decisiones del auditor sobre señales (HU-07). Solo se agregan filas; la vigente es la más reciente por señal.';
COMMENT ON COLUMN audit.decisiones.caso_id IS 'Caso al que pertenece la señal.';
COMMENT ON COLUMN audit.decisiones.senal_id IS 'Señal sobre la que se decide.';
COMMENT ON COLUMN audit.decisiones.decision IS 'relevante, descartada o pendiente.';
COMMENT ON COLUMN audit.decisiones.comentario IS 'Motivo del auditor; obligatorio al descartar.';
COMMENT ON COLUMN audit.decisiones.decidido_por IS 'Usuario que decidió; NULL hasta que exista autenticación.';
COMMENT ON COLUMN audit.decisiones.created_at IS 'Marca de tiempo UTC de la decisión.';

REVOKE ALL ON audit.senales, audit.decisiones FROM PUBLIC;
GRANT SELECT, INSERT ON audit.senales, audit.decisiones TO :"senales_backend_user";
GRANT USAGE, SELECT ON SEQUENCE audit.decisiones_id_seq TO :"senales_backend_user";

COMMIT;
