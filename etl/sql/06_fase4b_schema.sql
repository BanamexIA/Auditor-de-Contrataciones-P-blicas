CREATE TABLE IF NOT EXISTS clean.config_calidad (
    id SMALLINT PRIMARY KEY CHECK (id = 1),
    fecha_inicio_minima DATE NOT NULL,
    fecha_inicio_maxima DATE NOT NULL,
    fecha_descarga DATE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (fecha_inicio_maxima >= fecha_inicio_minima)
);

