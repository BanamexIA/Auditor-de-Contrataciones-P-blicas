CREATE TABLE IF NOT EXISTS clean.map_tipo_procedimiento (
    fuente TEXT NOT NULL CHECK (fuente IN ('comprasmx', 'historico')),
    prefijo TEXT NOT NULL,
    tipo_normalizado TEXT NOT NULL,
    prioridad INTEGER NOT NULL,
    estado TEXT NOT NULL,
    PRIMARY KEY (fuente, prefijo)
);

CREATE TABLE IF NOT EXISTS clean.contratos_excluidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fuente TEXT NOT NULL,
    motivo TEXT NOT NULL,
    tipo_expediente TEXT,
    tipo_procedimiento TEXT,
    tipo_procedimiento_norm TEXT,
    tipo_procedimiento_estado TEXT,
    ley TEXT,
    raw_payload JSONB NOT NULL,
    _source_file TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

