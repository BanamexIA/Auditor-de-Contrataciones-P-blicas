\set ON_ERROR_STOP on
-- Usuarios de la API (auditor y admin). Contraseñas con scrypt; nunca en claro.
\getenv usuarios_backend_user BACKEND_USER

BEGIN;

CREATE TABLE IF NOT EXISTS audit.usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario TEXT NOT NULL UNIQUE CHECK (usuario ~ '^[a-z0-9][a-z0-9._-]{1,39}$'),
    nombre TEXT,
    rol TEXT NOT NULL CHECK (rol IN ('auditor', 'admin')),
    hash_contrasena TEXT NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    ultimo_acceso TIMESTAMPTZ
);

COMMENT ON TABLE audit.usuarios IS
'Usuarios de la API. Alta y baja por CLI (python -m backend.usuarios). La baja no borra: activo = false.';
COMMENT ON COLUMN audit.usuarios.hash_contrasena IS
'scrypt$n$r$p$sal$hash (base64). Nunca la contraseña en claro.';

GRANT SELECT, INSERT, UPDATE ON audit.usuarios TO :"usuarios_backend_user";
GRANT USAGE, SELECT ON SEQUENCE audit.usuarios_id_seq TO :"usuarios_backend_user";

COMMIT;
